// Package gkrverifier generates the data tables of the ZkC GKR verifier from a circuit, and tests the
// verifier against gnark's.
package gkrverifier

import (
	"fmt"
	"io"
	"math/big"
	"strings"

	"github.com/consensys/gnark-crypto/field/koalabear"
	"github.com/consensys/gnark/constraint"
	"github.com/consensys/gnark/gkr"
)

// maxGateFrame is the number of slots of a gate's frame the interpreter in gate.zkc leaves to the
// gate's constants, inputs and instruction results.
const maxGateFrame = 126

// gateTables is the deduplicated gates of a circuit, in the layout of the tables in gate.zkc.
type gateTables struct {
	gateOfWire []int // the index of each wire's gate; -1 for an input wire
	gates      []gkr.GateBytecode
	nbIns      []int
}

// newGateTables deduplicates the gates of the non-input wires of the circuit. Gates are the same if they
// have the same bytecode and number of inputs.
func newGateTables(circuit gkr.SerializableCircuit) (*gateTables, error) {
	t := &gateTables{gateOfWire: make([]int, len(circuit))}
	index := make(map[string]int)
	for wireI, wire := range circuit {
		if wire.IsInput() {
			t.gateOfWire[wireI] = -1
			continue
		}
		gate, nbIn := wire.Gate.Evaluate, len(wire.Inputs)
		if frame := gate.EvaluatorSize(nbIn); frame > maxGateFrame {
			return nil, fmt.Errorf("wire %d: the gate needs a frame of %d slots, at most %d are available", wireI, frame, maxGateFrame)
		}
		key := fmt.Sprint(nbIn, gate.Constants, gate.Instructions)
		gateI, found := index[key]
		if !found {
			gateI = len(t.gates)
			index[key] = gateI
			t.gates = append(t.gates, gate)
			t.nbIns = append(t.nbIns, nbIn)
		}
		t.gateOfWire[wireI] = gateI
	}
	return t, nil
}

// felt returns the canonical representative of c in the base field.
func felt(c *big.Int) uint32 {
	var e koalabear.Element
	e.SetBigInt(c)
	return uint32(e.Uint64())
}

// WriteGateTables writes the gates of the circuit, deduplicated, as the static tables gate_info,
// gate_const, gate_inst and gate_arg that gate.zkc reads, and returns the index of the gate of each
// wire; -1 for input wires.
//
// A gate's instructions are the rows first_inst, …, first_inst + nb_inst - 1 of gate_inst, each
// giving the operation (a gkr.GateOp), the number of arguments and the first of its rows of gate_arg.
// An argument is a slot of the gate's frame: the constants, then the inputs, then the results of the
// instructions, as in gkr.GateInstruction.
func WriteGateTables(w io.Writer, circuit gkr.SerializableCircuit) ([]int, error) {
	t, err := newGateTables(circuit)
	if err != nil {
		return nil, err
	}

	var info, consts, insts, args []string
	for gateI, gate := range t.gates {
		info = append(info, fmt.Sprintf("(%d, %d, %d, %d, %d) // gate %d", len(gate.Constants), t.nbIns[gateI], len(gate.Instructions), len(insts), len(consts), gateI))
		for _, c := range gate.Constants {
			consts = append(consts, fmt.Sprintf("0x%08x", felt(c)))
		}
		for _, inst := range gate.Instructions {
			insts = append(insts, fmt.Sprintf("(%d, %d, %d) // %s", inst.Op, len(inst.Inputs), len(args), inst.Op))
			for _, slot := range inst.Inputs {
				args = append(args, fmt.Sprint(slot))
			}
		}
	}

	var sb strings.Builder
	sb.WriteString("// Code generated by gopkg/gkrverifier. DO NOT EDIT.\n\n")
	writeTable(&sb, "gate_info", "(nb_consts:u16, nb_in:u16, nb_inst:u16, first_inst:u16, first_const:u16)", "(0, 0, 0, 0, 0)", info)
	writeTable(&sb, "gate_const", "(constant:𝔽)", "0", consts)
	writeTable(&sb, "gate_inst", "(op:u16, nb_args:u16, first_arg:u16)", "(0, 0, 0)", insts)
	writeTable(&sb, "gate_arg", "(slot:u16)", "0", args)
	_, err = io.WriteString(w, sb.String())
	return t.gateOfWire, err
}

// writeTable writes a static table of the given rows, which are tuples when the table has several
// lanes. An empty table gets the row zero.
func writeTable(sb *strings.Builder, name, lanes, zero string, rows []string) {
	if len(rows) == 0 {
		rows = []string{zero}
	}
	fmt.Fprintf(sb, "static %s(row:u16) -> %s {\n", name, lanes)
	for i, row := range rows {
		sep := ","
		if i == len(rows)-1 {
			sep = ""
		}
		if comment := strings.Index(row, " //"); comment >= 0 {
			fmt.Fprintf(sb, "    %s%s%s\n", row[:comment], sep, row[comment:])
		} else {
			fmt.Fprintf(sb, "    %s%s\n", row, sep)
		}
	}
	sb.WriteString("}\n\n")
}

// maxLagrangeDegree is the largest degree the table lagrange_inv_denominator can index.
const maxLagrangeDegree = 15

// maxLevelDegree returns the largest number of values per round polynomial that the levels of the
// schedule have.
func maxLevelDegree(circuit gkr.SerializableCircuit, schedule constraint.GkrProvingSchedule) int {
	identity := gkr.SerializableGate{Evaluate: gkr.IdentityBytecode(), NbIn: 1, Degree: 1}
	res := 0
	for levelI, level := range schedule {
		res = max(res, circuit.LevelCircuit(schedule, levelI, identity).ZeroCheckDegree(level))
	}
	return res
}

// WriteLagrangeTables writes the static table lagrange_inv_denominator that round.zkc reads: for
// every degree d up to the largest that the schedule's levels have, and 0 ≤ i ≤ d, the inverse of
// ∏_{k≠i}(i − k), the denominator of the i-th Lagrange polynomial on {0, …, d}. The row of d and i
// is 16d + i; the rows with i > d are zero.
func WriteLagrangeTables(w io.Writer, circuit gkr.SerializableCircuit, schedule constraint.GkrProvingSchedule) error {
	maxDegree := maxLevelDegree(circuit, schedule)
	if maxDegree > maxLagrangeDegree {
		return fmt.Errorf("a level has %d values per round polynomial, at most %d are supported", maxDegree, maxLagrangeDegree)
	}

	var rows []string
	for d := 0; d <= maxDegree; d++ {
		for i := 0; i <= maxLagrangeDegree; i++ {
			var inverse koalabear.Element
			if i <= d {
				var denominator koalabear.Element
				denominator.SetOne()
				for k := 0; k <= d; k++ {
					if k != i {
						var factor koalabear.Element
						factor.SetInt64(int64(i - k))
						denominator.Mul(&denominator, &factor)
					}
				}
				inverse.Inverse(&denominator)
			}
			rows = append(rows, fmt.Sprintf("0x%08x", inverse.Uint64()))
		}
	}

	var sb strings.Builder
	sb.WriteString("// Code generated by gopkg/gkrverifier. DO NOT EDIT.\n\n")
	fmt.Fprintf(&sb, "static lagrange_inv_denominator(d:u4, i:u4) -> (inverse:𝔽) {\n")
	for i, row := range rows {
		sep := ","
		if i == len(rows)-1 {
			sep = ""
		}
		fmt.Fprintf(&sb, "    %s%s\n", row, sep)
	}
	sb.WriteString("}\n")
	_, err := io.WriteString(w, sb.String())
	return err
}
