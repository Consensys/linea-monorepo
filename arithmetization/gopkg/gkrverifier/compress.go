package gkrverifier

import (
	"fmt"
	"io"
	"strings"
)

// The parameters of the Poseidon2 permutation of poseidon2.zkc.
const (
	poseidon2Width         = 16
	poseidon2HalfFull      = 3
	poseidon2PartialRounds = 21
)

// compressBuilder writes the straight-line body of the Poseidon2 compression, each operation
// assigning a fresh variable.
type compressBuilder struct {
	sb    strings.Builder
	nbVar int
	state [poseidon2Width]string // the variable holding each lane of the state
}

// emit declares a new variable holding the expression, and returns its name.
func (b *compressBuilder) emit(expr string) string {
	name := fmt.Sprintf("v%d", b.nbVar)
	b.nbVar++
	fmt.Fprintf(&b.sb, "    var %s:𝔽 = %s\n", name, expr)
	return name
}

func (b *compressBuilder) add(x, y string) string { return b.emit(x + " + " + y) }

// sbox returns x³.
func (b *compressBuilder) sbox(x string) string { return b.emit(b.emit(x+" * "+x) + " * " + x) }

// matMulM4 applies the 4×4 matrix of poseidon2.zkc to each chunk of the state.
func (b *compressBuilder) matMulM4() {
	for c := 0; c < poseidon2Width; c += 4 {
		x0, x1, x2, x3 := b.state[c], b.state[c+1], b.state[c+2], b.state[c+3]
		t01 := b.add(x0, x1)
		t23 := b.add(x2, x3)
		t0123 := b.add(t01, t23)
		t01123 := b.add(t0123, x1)
		t01233 := b.add(t0123, x3)
		b.state[c+3] = b.add(b.add(x0, x0), t01233)
		b.state[c+1] = b.add(b.add(x2, x2), t01123)
		b.state[c+0] = b.add(t01, t01123)
		b.state[c+2] = b.add(t23, t01233)
	}
}

// matMulExternal applies the external linear layer: M4 on each chunk, then each chunk gets the
// sums, across chunks, of the lanes at the same place.
func (b *compressBuilder) matMulExternal() {
	b.matMulM4()
	var sums [4]string
	for j := range sums {
		sums[j] = b.add(b.add(b.add(b.state[j], b.state[4+j]), b.state[8+j]), b.state[12+j])
	}
	for c := 0; c < poseidon2Width; c += 4 {
		for j := range sums {
			b.state[c+j] = b.add(b.state[c+j], sums[j])
		}
	}
}

// matMulInternal applies the internal linear layer: σ'[i] = Σⱼ σ[j] + internal_diag[i]·σ[i].
func (b *compressBuilder) matMulInternal() {
	sum := b.state[0]
	for i := 1; i < poseidon2Width; i++ {
		sum = b.add(sum, b.state[i])
	}
	for i := range b.state {
		b.state[i] = b.emit(fmt.Sprintf("%s + (internal_diag[%d] * %s)", sum, i, b.state[i]))
	}
}

// fullRound is the round with the index r among the rounds of the permutation.
func (b *compressBuilder) fullRound(r int) {
	for i := range b.state {
		b.state[i] = b.sbox(b.emit(fmt.Sprintf("%s + round_keys[%d]", b.state[i], r*poseidon2Width+i)))
	}
	b.matMulExternal()
}

func (b *compressBuilder) partialRound(r int) {
	b.state[0] = b.sbox(b.emit(fmt.Sprintf("%s + round_keys[%d]", b.state[0], r*poseidon2Width)))
	b.matMulInternal()
}

// WriteCompressNative writes poseidon2.zkc's permutation as the body of the native function
// poseidon2_compress, with no loops and no calls, so that the module it makes has one row per
// call and no other module has any rows for it. The function maps (x₀, …, x₁₅) to
// P(x)[8..16] + (x₈, …, x₁₅), which is the compression of the blocks (x₀, …, x₇) and (x₈, …, x₁₅).
func WriteCompressNative(w io.Writer) error {
	var b compressBuilder
	for i := range b.state {
		b.state[i] = fmt.Sprintf("x%d", i)
	}

	b.matMulExternal()
	for r := range poseidon2HalfFull {
		b.fullRound(r)
	}
	for r := range poseidon2PartialRounds {
		b.partialRound(poseidon2HalfFull + r)
	}
	for r := range poseidon2HalfFull {
		b.fullRound(poseidon2HalfFull + poseidon2PartialRounds + r)
	}

	var params, results []string
	for i := range poseidon2Width {
		params = append(params, fmt.Sprintf("x%d:𝔽", i))
	}
	for i := range poseidon2Width / 2 {
		results = append(results, fmt.Sprintf("y%d:𝔽", i))
	}

	var sb strings.Builder
	sb.WriteString("// Code generated by gopkg/gkrverifier. DO NOT EDIT.\n\n")
	sb.WriteString("include \"constants.zkc\"\n\n")
	sb.WriteString("// poseidon2_compress returns the compression C(l, r) = P(l ‖ r)[8..16] + r of the blocks l = (x₀, …, x₇)\n")
	sb.WriteString("// and r = (x₈, …, x₁₅), for the permutation P of poseidon2.zkc. Its body is that permutation without\n")
	sb.WriteString("// loops or calls, as the trace of a native function has the rows of the functions that it calls.\n")
	sb.WriteString("#[native]\n")
	fmt.Fprintf(&sb, "fn poseidon2_compress(%s) -> (%s) {\n", strings.Join(params, ", "), strings.Join(results, ", "))
	sb.WriteString(b.sb.String())
	for i := range poseidon2Width / 2 {
		fmt.Fprintf(&sb, "    y%d = %s + x%d\n", i, b.state[poseidon2Width/2+i], poseidon2Width/2+i)
	}
	sb.WriteString("}\n")
	_, err := io.WriteString(w, sb.String())
	return err
}
