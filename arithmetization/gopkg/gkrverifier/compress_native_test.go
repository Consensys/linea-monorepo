package gkrverifier

import (
	"bytes"
	"flag"
	"os"
	"testing"
)

var update = flag.Bool("update", false, "rewrite the generated ZkC files that are checked in")

const compressNativeFile = "../../src/main/lib/poseidon2/compress_native.zkc"

// TestCompressNativeIsGenerated checks that compress_native.zkc is what WriteCompressNative writes.
// Run it with -update to rewrite the file.
func TestCompressNativeIsGenerated(t *testing.T) {
	var generated bytes.Buffer
	if err := WriteCompressNative(&generated); err != nil {
		t.Fatal(err)
	}
	if *update {
		if err := os.WriteFile(compressNativeFile, generated.Bytes(), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	checkedIn, err := os.ReadFile(compressNativeFile)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(checkedIn, generated.Bytes()) {
		t.Errorf("%s is not what WriteCompressNative writes: run go test -run TestCompressNativeIsGenerated -update", compressNativeFile)
	}
}
